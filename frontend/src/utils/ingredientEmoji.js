export const getIngredientEmoji = (ingredient) => {
    const name = ingredient?.ingredientName ?? (typeof ingredient === 'string' ? ingredient : '');

    if (INGREDIENT_EMOJI[name]) return INGREDIENT_EMOJI[name];

    const found = KEYWORD_EMOJI.find(([kw]) => name.includes(kw));
    if (found) return found[1];

    const top = ingredient?.topCategory ?? '';
    if (CATEGORY_EMOJI[top]) return CATEGORY_EMOJI[top];

    return '🍽️';
};
